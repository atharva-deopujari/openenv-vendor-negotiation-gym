class ScenarioDatabase:
    """Database of negotiation scenarios for the Vendor Negotiation Gym."""

    def __init__(self):
        self.scenarios = SCENARIOS

    def get_random_scenario(self, seed=None):
        """Return a random scenario, optionally using a seed for reproducibility."""
        if seed is not None:
            rng = random.Random(seed)
            return rng.choice(self.scenarios)
        return random.choice(self.scenarios)

    def get_scenario_by_id(self, scenario_id):
        """Return a scenario by its ID, or None if not found."""
        for s in self.scenarios:
            if s["id"] == scenario_id:
                return s
        return None

    def get_scenarios_by_type(self, cp_type):
        """Return all scenarios matching a given counterparty_type."""
        return [s for s in self.scenarios if s["counterparty_type"] == cp_type]

    def get_all_types(self):
        """Return a set of all counterparty types present in the database."""
        return set(s["counterparty_type"] for s in self.scenarios)

    def summary(self):
        """Return a dict mapping counterparty_type to count."""
        counts = {}
        for s in self.scenarios:
            t = s["counterparty_type"]
            counts[t] = counts.get(t, 0) + 1
        return counts

    def __len__(self):
        return len(self.scenarios)
